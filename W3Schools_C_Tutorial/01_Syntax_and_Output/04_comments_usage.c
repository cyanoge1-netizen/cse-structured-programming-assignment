#include <stdio.h>

/**
 * W3Schools C Tutorial: Comments
 * Concept: Using single-line comments and multi-line comments.
 */
int main(void) {
    // This is a single-line comment
    printf("Comments are ignored by the compiler.\n");

    /* This is a multi-line comment.
       It can span across several lines
       to explain complex logic or code purpose. */
    printf("Code readability is essential in C programming.\n");
    return 0;
}
