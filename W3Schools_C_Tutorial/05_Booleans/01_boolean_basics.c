#include <stdio.h>
#include <stdbool.h>

/**
 * W3Schools C Tutorial: Booleans
 * Concept: Using <stdbool.h>, declaring boolean variables, and printing them.
 */
int main(void) {
    bool isProgrammingFun = true;
    bool isFishTasty = false;

    printf("isProgrammingFun : %d\n", isProgrammingFun); // Prints 1
    printf("isFishTasty       : %d\n", isFishTasty);       // Prints 0

    return 0;
}
