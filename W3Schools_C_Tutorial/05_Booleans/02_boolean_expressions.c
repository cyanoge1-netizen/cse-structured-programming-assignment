#include <stdio.h>
#include <stdbool.h>

/**
 * W3Schools C Tutorial: Comparing Values and Expressions
 * Concept: Boolean expressions returning truth values directly.
 */
int main(void) {
    int x = 10;
    int y = 9;

    printf("10 > 9  : %d\n", x > y);
    printf("10 == 9 : %d\n", x == y);
    printf("10 == 10: %d\n", 10 == 10);

    return 0;
}
