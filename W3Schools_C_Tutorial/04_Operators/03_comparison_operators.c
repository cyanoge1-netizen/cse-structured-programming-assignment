#include <stdio.h>

/**
 * W3Schools C Tutorial: Comparison Operators
 * Concept: Relational comparisons returning 1 (true) or 0 (false).
 */
int main(void) {
    int x = 5;
    int y = 3;

    printf("x = %d, y = %d\n", x, y);
    printf("x > y  : %d\n", x > y);
    printf("x < y  : %d\n", x < y);
    printf("x == y : %d\n", x == y);
    printf("x != y : %d\n", x != y);
    printf("x >= y : %d\n", x >= y);
    printf("x <= y : %d\n", x <= y);

    return 0;
}
